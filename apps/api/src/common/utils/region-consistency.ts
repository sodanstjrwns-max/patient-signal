// 역인덱스: 동 기본형 → 소속 구 목록 (동명이동 대비 배열)
const DONG_TO_GUS: Map<string, string[]> = (() => {
  const map = new Map<string, string[]>();
  for (const [gu, dongs] of Object.entries(SEOUL_GU_DONGS)) {
    for (const dong of dongs) {
      const list = map.get(dong) || [];
      list.push(gu);
      map.set(dong, list);
    }
  }
  return map;
})();

/**
 * 동 표기 정규화: "당산1동"→"당산동", "성수동2가"→"성수동", "잠실 6동"→"잠실동"
 */
export function normalizeDong(raw: string): string {
  let t = (raw || '').trim().replace(/\s+/g, '');
  if (!t) return '';
  t = t.replace(/동(\d+)가$/, '동'); // 성수동2가 → 성수동
  t = t.replace(/(\d+)동$/, '동'); // 당산1동 → 당산동
  t = t.replace(/본동$/, (m, offset) => (offset > 0 ? '동' : m)); // 잠실본동 → 잠실동 (단독 '본동'은 유지)
  return t;
}

/**
 * 동이 현재 시군구 소속으로 볼 수 있는지 검증 (best-effort)
 *
 * @returns true  = 일관되거나 판단 불가(유지)
 *          false = 서울 내에서 다른 구 소속으로 확인됨(무시해야 함)
 */
export function isDongConsistentWithSigungu(
  regionSido: string | null | undefined,
  regionSigungu: string | null | undefined,
  regionDong: string | null | undefined,
): boolean {
  const dong = normalizeDong(regionDong || '');
  const sigungu = (regionSigungu || '').trim();
  if (!dong || !sigungu) return true; // 검증 대상 없음

  // 검증 데이터는 서울만 보유 — 서울 외 지역은 판단 불가로 유지
  const sido = (regionSido || '').trim();
  if (sido && !sido.includes('서울')) return true;

  // 병원의 구가 맵에 없는 경우(비표준 표기 등) 판단 불가로 유지
  const ownDongs = SEOUL_GU_DONGS[sigungu];
  if (!ownDongs) return true;

  // 자기 구 목록에 있으면 일관
  if (ownDongs.includes(dong) || ownDongs.includes(normalizeDong(dong))) return true;

  // 다른 구 소속으로만 확인되면 불일치
  const foundGus = DONG_TO_GUS.get(dong);
  if (foundGus && !foundGus.includes(sigungu)) return false;

  // 맵에 아예 없는 동 → 판단 불가, 유지
  return true;
}
